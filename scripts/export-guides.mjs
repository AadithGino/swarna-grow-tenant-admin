/**
 * Writes the Sidekick guide catalogue for the backend from the portal's tour registry,
 * so Sidekick always offers exactly the guides the portal can run.
 *
 *   pnpm guides:export
 *
 * Output: ../backend/src/services/assistant/agent/guide-catalog.js
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { createServer } from "vite";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.resolve(root, "../swarnagrow-backend/src/services/assistant/agent/guide-catalog.js");

const server = await createServer({
  root,
  configFile: false,
  logLevel: "error",
  server: { middlewareMode: true, hmr: false, watch: null },
  resolve: { alias: { "@": root } },
  optimizeDeps: { noDiscovery: true, include: [] },
});
try {
  const { buildGuideCatalog } = await server.ssrLoadModule("/src/lib/tours/catalog.ts");
  const catalog = buildGuideCatalog();
  const body = `// Generated by admin/scripts/export-guides.mjs from admin/src/lib/tours — do not edit by hand.\n// Run \`pnpm guides:export\` in admin/ after changing guides.\nexport const GUIDE_CATALOG = Object.freeze(${JSON.stringify(catalog, null, 2)});\n`;
  writeFileSync(out, body);
  console.log(`wrote ${catalog.length} guides → ${path.relative(root, out)}`);
} finally {
  await server.close();
}
