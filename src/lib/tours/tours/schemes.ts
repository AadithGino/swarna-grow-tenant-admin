/** Move the plan builder to one of its steps (click the step, or Continue after filling the current one). */
function wizardStep(stepId: string, label: string, body: string): TourStep {
  return {
    id: `go-${stepId}`,
    target: `plan-step:${stepId}`,
    title: `Go to ${label}`,
    body: `${body} Fill in this page, then press Continue, or click ${label} above.`,
    advance: "selected",
    placement: "bottom",
  };
}

function wizardField(id: string, label: string, title: string, body: string, example?: string, extra: Partial<TourStep> = {}): TourStep {
  return { id, target: "plan-wizard-form", field: label, title, body, ...(example ? { example } : {}), ...extra };
}

function wizardChoice(id: string, text: string, title: string, body: string): TourStep {
  return { id, target: "plan-wizard-form", text, title, body: `${body} Click it to choose.`, advance: "click" };
}

