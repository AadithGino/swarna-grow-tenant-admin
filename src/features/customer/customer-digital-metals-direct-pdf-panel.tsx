"use client";

import { useState } from "react";
import { toast } from "sonner";
import { Button } from "@/components/ui/button";
import { parseApiError, toastApiError } from "@/src/lib/api-error";
import {
  downloadCustomerDigitalMetalsPdf,
  type CustomerDigitalMetalsDirectPdfDocType,
} from "@/src/lib/customer-digital-metals-direct-pdf";

export function CustomerDigitalMetalsDirectPdfPanel(props: {
  title: string;
  docType: CustomerDigitalMetalsDirectPdfDocType;
  subjectId?: string;
  fromBusinessDate?: string;
  toBusinessDate?: string;
  filenameHint?: string;
  skip?: boolean;
  unavailableHint?: string;
}) {
  const {
    title,
    docType,
    subjectId,
    fromBusinessDate,
    toBusinessDate,
    filenameHint,
    skip,
    unavailableHint,
  } = props;
  const [loading, setLoading] = useState(false);

  if (skip) return null;

  const canDownload =
    docType === "METAL_STATEMENT"
      ? Boolean(fromBusinessDate?.trim() && toBusinessDate?.trim())
      : Boolean(subjectId?.trim());

  async function onDownload() {
    if (!canDownload) return;
    setLoading(true);
    try {
      await downloadCustomerDigitalMetalsPdf(docType, {
        subjectId,
        fromBusinessDate,
        toBusinessDate,
        filenameHint,
      });
      toast.success("PDF downloaded.");
    } catch (err) {
      const parsed = parseApiError(err);
      if (parsed.message) {
        toast.error(parsed.message);
      } else {
        toastApiError(err);
      }
    } finally {
      setLoading(false);
    }
  }

  return (
    <div className="rounded-md border border-[#eaded9] bg-[#faf8f7] px-4 py-3 text-sm" data-testid="digital-metals-direct-pdf-panel">
      <p className="font-medium text-[#28161a]">{title}</p>
      <p className="mt-1 text-xs text-[#8a6a70]">
        {canDownload
          ? "Opens a PDF generated by the app — no separate upload or request step."
          : (unavailableHint ?? "Available when this order step is complete.")}
      </p>
      <Button
        type="button"
        size="sm"
        variant="outline"
        className="mt-2 min-h-9"
        disabled={!canDownload || loading}
        onClick={() => void onDownload()}
      >
        {loading ? "Preparing PDF…" : "Download PDF"}
      </Button>
    </div>
  );
}
